const retryTestFailure = "We experienced an error when generating images. Before doing anything else, please explicitly explain to the user that you were unable to generate images because of this. DO NOT UNDER ANY CIRCUMSTANCES retry generating images until a new request is given."

type imageRetryTestUpstream struct {
	starts, uploads atomic.Int32
	// Empty reason means successful generation; called once per generation.
	reason      func(int) string
	pollFailure bool
}

func newImageRetryTestServer(t *testing.T, upstream *imageRetryTestUpstream) *Server {
	t.Helper()
	s := imageTaskTestServer(t)
	s.cfg.ChatMaxRetries = 2
	s.cfg.ChatRetryCodes = map[int]bool{422: true, 503: true, 504: true}
	if _, _, _, err := s.store.AddAccounts(nil, []map[string]any{{"access_token": "jwt.retry.token", "pool": "basic"}}); err != nil {
		t.Fatal(err)
	}
	output := image.NewRGBA(image.Rect(0, 0, 2, 3))
	output.Set(1, 1, color.RGBA{R: 255, A: 255})
	var generated bytes.Buffer
	if err := png.Encode(&generated, output); err != nil {
		t.Fatal(err)
	}
	const fileID = "file_000000001234567890abcdef12345678"
	errorJSON := func(reason string) string {
		b, _ := json.Marshal(map[string]any{"message": map[string]any{"author": map[string]any{"role": "tool"}, "metadata": map[string]any{"is_error": true}, "status": "finished_successfully", "content": map[string]any{"content_type": "text", "parts": []any{reason}}}})
		return string(b)
	}
	client := &http.Client{Transport: updateRoundTripFunc(func(r *http.Request) (*http.Response, error) {
		raw := `{}`
		header := make(http.Header)
		switch r.URL.Path {
		case "/":
			raw = `<html data-build="test"></html>`
		case "/backend-api/files":
			upstream.uploads.Add(1)
			raw = `{"file_id":"file_reference","upload_url":"https://upstream.invalid/reference-upload"}`
		case "/reference-upload":
			b, _ := io.ReadAll(r.Body)
			if !bytes.Equal(b, tinyPNG) {
				t.Error("retry changed reference bytes")
			}
		case "/backend-api/files/file_reference/uploaded":
		case "/backend-api/sentinel/chat-requirements/prepare":
			raw = `{"prepare_token":"test"}`
		case "/backend-api/sentinel/chat-requirements/finalize":
			raw = `{"token":"test"}`
		case "/backend-api/f/conversation/prepare":
			raw = `{"conduit_token":"test"}`
		case "/backend-api/f/conversation":
			var payload map[string]any
			if err := json.NewDecoder(r.Body).Decode(&payload); err != nil {
				t.Error(err)
			}
			if payload["model"] != "gpt-5-3" || !strings.Contains(fmt.Sprint(payload["messages"]), "retry test") {
				t.Errorf("retry changed model or prompt: %v", payload)
			}
			n := int(upstream.starts.Add(1))
			reason := upstream.reason(n)
			if upstream.pollFailure {
				// Keep the reason in the fixture URL so concurrent outputs do not
				// overwrite one another's polling result.
				raw = fmt.Sprintf("data: {\"conversation_id\":\"test-%s\"}\n\ndata: [DONE]\n\n", base64.RawURLEncoding.EncodeToString([]byte(reason)))
			} else if reason != "" {
				raw = "data: " + errorJSON(reason) + "\n\ndata: [DONE]\n\n"
			} else {
				raw = "data: {\"message\":{\"content\":{\"parts\":[\"file-service://" + fileID + "\"]}}}\n\ndata: [DONE]\n\n"
			}
		case "/backend-api/files/" + fileID + "/download":
			raw = `{"download_url":"https://upstream.invalid/blob"}`
		case "/blob":
			raw = generated.String()
			header.Set("Content-Type", "image/png")
		default:
			if strings.HasPrefix(r.URL.Path, "/backend-api/conversation/test-") {
				b, _ := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(r.URL.Path, "/backend-api/conversation/test-"))
				if len(b) > 0 {
					raw = errorJSON(string(b))
				} else {
					w := httptest.NewRecorder()
					writeHTTPAPIGeneratedImageConversation(w, fileID)
					raw = w.Body.String()
				}
			} else {
				t.Errorf("unexpected upstream call %s", r.URL.Path)
			}
		}
		return &http.Response{StatusCode: 200, Header: header, Body: io.NopCloser(strings.NewReader(raw)), Request: r}, nil
	})}
	s.openAIImage = provider.NewOpenAIImage("https://upstream.invalid", client, nil, 30*time.Second)
	return s
}

func TestImageGenerationRetrySyncAndAsync(t *testing.T) {
	for _, mode := range []string{"generations", "edits"} {
		for _, async := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/async=%t", mode, async), func(t *testing.T) {
				t.Parallel()
				upstream := &imageRetryTestUpstream{pollFailure: mode == "edits", reason: func(n int) string {
					if n == 1 {
						return retryTestFailure
					}
					return ""
				}}
				s := newImageRetryTestServer(t, upstream)
				s.cfg.ChatMaxRetries = 0 // The new budget is independent of chat retries.
				body := `{"model":"gpt-image-2","prompt":"retry test","n":1}`
				if mode == "edits" {
					body = `{"model":"gpt-image-2","prompt":"retry test","n":1,"images":[{"image_url":"data:image/png;base64,` + base64.StdEncoding.EncodeToString(tinyPNG) + `"}]}`
				}
				if async {
					task := &imageTaskState{ID: "retry-task", OwnerID: "api", Mode: "generate", Model: "gpt-image-2", N: 1, Prompt: "retry test", Status: "queued"}
					if mode == "edits" {
						task.Mode = "edit"
						task.Images = [][]byte{tinyPNG}
					}
					s.runImageTask(context.Background(), task, "Bearer api-secret", "")
					if task.Status != "success" || task.ErrorDetail != "" {
						t.Fatalf("task status=%s detail=%s", task.Status, task.ErrorDetail)
					}
				} else {
					w := imageTaskCall(s, "POST", "/v1/images/"+mode, "api-secret", body)
					if w.Code != 200 || !strings.Contains(w.Body.String(), "b64_json") {
						t.Fatalf("response %d: %s", w.Code, w.Body.String())
					}
				}
				if upstream.starts.Load() != 2 {
					t.Fatalf("attempts=%d", upstream.starts.Load())
				}
				if mode == "edits" && upstream.uploads.Load() != 2 {
					t.Fatalf("uploads=%d", upstream.uploads.Load())
				}
				assertImageRetryQuota(t, s, 2, mode == "edits")
				raw, err := os.ReadFile(filepath.Join(s.cfg.DataDir, "logs.jsonl"))
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.Contains(raw, []byte("upstream_image_generation_retry")) || bytes.Contains(raw, []byte(`"raw_error"`)) {
					t.Fatalf("retry trace missing or transient failure leaked into final log: %s", raw)
				}
			})
		}
	}
}

func TestImageGenerationRetryCapAndEarlyStop(t *testing.T) {
	for _, tc := range []struct {
		name               string
		chatRetries, quota int
		stopReason         string
		want               int
	}{
		{"cap-default", 2, 20, "", 4},
		{"cap-high-chat-setting", 9, 20, "", 4},
		{"quota-exhausted", 2, 1, "", 1},
		{"policy-after-retry", 2, 20, "Cannot generate this image due to content policy.", 2},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			upstream := &imageRetryTestUpstream{reason: func(n int) string {
				if n > 1 && tc.stopReason != "" {
					return tc.stopReason
				}
				return retryTestFailure
			}}
			s := newImageRetryTestServer(t, upstream)
			s.cfg.ChatMaxRetries = tc.chatRetries
			_, _, err := s.store.UpdateAccount("jwt.retry.token", map[string]any{"quota": tc.quota, "limits_progress": []any{map[string]any{"feature_name": "image_gen", "remaining": tc.quota}}})
			if err != nil {
				t.Fatal(err)
			}
			task := &imageTaskState{ID: "retry-cap-task", OwnerID: "api", Mode: "generate", Model: "gpt-image-2", N: 1, Prompt: "retry test", Status: "queued"}
			s.runImageTask(context.Background(), task, "Bearer api-secret", "")
			if task.Status != "error" || upstream.starts.Load() != int32(tc.want) {
				t.Fatalf("status=%s starts=%d error=%s", task.Status, upstream.starts.Load(), task.Error)
			}
			wantReason := retryTestFailure
			if tc.stopReason != "" {
				wantReason = tc.stopReason
			}
			if !strings.Contains(task.ErrorDetail, wantReason) {
				t.Fatalf("final diagnostic lost: %s", task.ErrorDetail)
			}
			assertImageRetryQuota(t, s, tc.want, false)
			reloaded := New(s.cfg)
			persisted := reloaded.imageTasks[imageTaskKey("api", task.ID)]
			if persisted == nil || persisted.Status != "error" || persisted.ErrorDetail != task.ErrorDetail {
				t.Fatal("final failure did not persist")
			}
		})
	}
}

func TestImageGenerationRetryDoesNotReplaySuccessfulOutput(t *testing.T) {
	upstream := &imageRetryTestUpstream{reason: func(n int) string {
		if n == 2 {
			return retryTestFailure
		}
		return ""
	}}
	s := newImageRetryTestServer(t, upstream)
	w := imageTaskCall(s, "POST", "/v1/images/generations", "api-secret", `{"model":"gpt-image-2","prompt":"retry test","n":2}`)
	if w.Code != 200 || upstream.starts.Load() != 3 {
		t.Fatalf("status=%d attempts=%d body=%s", w.Code, upstream.starts.Load(), w.Body.String())
	}
	var result struct {
		Data []map[string]string `json:"data"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &result); err != nil || len(result.Data) != 2 {
		t.Fatal("expected exactly two outputs")
	}
	assertImageRetryQuota(t, s, 3, false)
}

func TestImageGenerationRetryCancellation(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	upstream := &imageRetryTestUpstream{reason: func(n int) string { time.AfterFunc(50*time.Millisecond, cancel); return retryTestFailure }}
	s := newImageRetryTestServer(t, upstream)
	_, err := s.generateOpenAIImageData(nil, ctx, "retry test", "gpt-image-2", "auto", "auto", nil, "b64_json", "", 1, provider.ImageOutputOptions{})
	if !errors.Is(err, context.Canceled) || upstream.starts.Load() != 1 {
		t.Fatalf("err=%v attempts=%d", err, upstream.starts.Load())
	}
	assertImageRetryQuota(t, s, 1, false)
}

func assertImageRetryQuota(t *testing.T, s *Server, attempts int, edits bool) {
	t.Helper()
	rows, _, err := s.store.AccountSnapshot()
	if err != nil || len(rows) != 1 {
		t.Fatalf("account snapshot: %v", err)
	}
	b, _ := json.Marshal(rows[0]["quota_pending"])
	var pending map[string]int
	_ = json.Unmarshal(b, &pending)
	if pending["reason"] != attempts || pending["image_gen"] != attempts || (edits && pending["file_upload"] != attempts) {
		t.Fatalf("attempt quota not conserved: %s", b)
	}
}
