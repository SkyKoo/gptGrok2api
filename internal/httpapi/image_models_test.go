func TestDirectImageModelsSyncAsyncAndEdits(t *testing.T) {
	for _, model := range []string{"gpt-image-2.5-sunburst", "gpt-image-2.5-flare", "gpt-image-2.6-sunburst", "gpt-image-2.6-flare"} {
		for _, path := range []string{"/v1/images/generations", "/v1/images/edits", "/api/image-tasks/generations", "/api/image-tasks/edits"} {
			t.Run(model+path, func(t *testing.T) {
				s := imageTaskTestServer(t)
				output := image.NewNRGBA(image.Rect(0, 0, 3, 2))
				output.Set(1, 1, color.NRGBA{B: 255, A: 255})
				var generated bytes.Buffer
				if err := png.Encode(&generated, output); err != nil {
					t.Fatal(err)
				}
				_, _, _, err := s.store.AddAccounts(nil, []map[string]any{{"access_token": "jwt.header.payload", "email": "direct@example.test", "pool": "basic"}})
				if err != nil {
					t.Fatal(err)
				}
				// Neither the explicit image model nor this stale legacy setting is in the chat catalog.
				_, _ = s.store.UpdateConfig("openai_routing", map[string]any{"image_conversation_model": "unavailable-legacy-chat"})
				var prepares, calls atomic.Int32
				var upstream *httptest.Server
				upstream = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					switch r.URL.Path {
					case "/":
						io.WriteString(w, `<html data-build="test"></html>`)
					case "/backend-api/sentinel/chat-requirements/prepare":
						writeJSON(w, 200, map[string]any{"prepare_token": "test"})
					case "/backend-api/sentinel/chat-requirements/finalize":
						writeJSON(w, 200, map[string]any{"token": "test"})
					case "/backend-api/files":
						writeJSON(w, 200, map[string]any{"file_id": "file_reference", "upload_url": upstream.URL + "/upload"})
					case "/upload":
						w.WriteHeader(201)
					case "/backend-api/files/file_reference/uploaded":
						writeJSON(w, 200, map[string]any{"status": "success"})
					case "/backend-api/f/conversation/prepare", "/backend-api/f/conversation":
						var body map[string]any
						if json.NewDecoder(r.Body).Decode(&body) != nil || body["model"] != model {
							t.Error("requested model was substituted", body["model"])
						}
						if strings.HasSuffix(r.URL.Path, "/prepare") {
							prepares.Add(1)
							writeJSON(w, 200, map[string]any{"status": "ok", "conduit_token": nil})
							return
						}
						calls.Add(1)
						if _, ok := r.Header["X-Conduit-Token"]; ok {
							t.Error("empty conduit header sent")
						}
						raw, _ := json.Marshal(body)
						if strings.HasSuffix(path, "/edits") && !bytes.Contains(raw, []byte("file_reference")) {
							t.Error("reference missing from edit")
						}
						w.Header().Set("Content-Type", "text/event-stream")
						fmt.Fprintf(w, "data: {\"conversation_id\":\"conversation-1\",\"message\":{\"metadata\":{\"model_slug\":%q}}}\n\ndata: [DONE]\n\n", model)
					case "/backend-api/conversation/conversation-1":
						writeHTTPAPIGeneratedImageConversation(w, "file_result")
					case "/backend-api/files/file_result/download":
						writeJSON(w, 200, map[string]any{"download_url": upstream.URL + "/blob"})
					case "/blob":
						w.Header().Set("Content-Type", "image/png")
						w.Write(generated.Bytes())
					default:
						t.Error("unexpected upstream request", r.URL.Path)
						http.NotFound(w, r)
					}
				}))
				defer upstream.Close()
				s.openAIImage = provider.NewOpenAIImage(upstream.URL, upstream.Client(), nil, 30*time.Second)
				fields := map[string]any{"client_task_id": "direct-model", "model": model, "prompt": "blue ball", "n": 1, "output_format": "png"}
				w := httptest.NewRecorder()
				s.Handler().ServeHTTP(w, imageOutputRequest(t, path, "json", fields))
				async := strings.HasPrefix(path, "/api/")
				if async {
					if w.Code != 202 {
						t.Fatalf("submit: %d %s", w.Code, w.Body.String())
					}
					deadline := time.Now().Add(5 * time.Second)
					for {
						w = imageTaskCall(s, "GET", "/api/image-tasks/direct-model", "api-secret", "")
						var task imageTaskState
						json.Unmarshal(w.Body.Bytes(), &task)
						if task.Status == "success" || task.Status == "error" {
							break
						}
						if time.Now().After(deadline) {
							t.Fatal("async timeout")
						}
						time.Sleep(10 * time.Millisecond)
					}
				}
				var result struct {
					Data   []map[string]string `json:"data"`
					Status string              `json:"status"`
					Model  string              `json:"model"`
				}
				if w.Code != 200 || json.Unmarshal(w.Body.Bytes(), &result) != nil || len(result.Data) != 1 || (async && (result.Status != "success" || result.Model != model)) {
					t.Fatalf("result: %d %s", w.Code, w.Body.String())
				}
				var raw []byte
				if async {
					imageResponse := adminRequest(s.Handler(), "GET", result.Data[0]["url"], nil)
					if imageResponse.Code != 200 || imageResponse.Header().Get("Content-Type") != "image/png" {
						t.Fatal("saved output not downloadable")
					}
					raw = imageResponse.Body.Bytes()
					reloaded := New(s.cfg)
					replay := httptest.NewRecorder()
					reloaded.Handler().ServeHTTP(replay, imageOutputRequest(t, path, "json", fields))
					if replay.Code != 200 && replay.Code != 202 {
						t.Fatalf("restart replay: %d %s", replay.Code, replay.Body.String())
					}
					fields["model"] = "gpt-image-2"
					conflict := httptest.NewRecorder()
					reloaded.Handler().ServeHTTP(conflict, imageOutputRequest(t, path, "json", fields))
					if conflict.Code != 409 {
						t.Fatal("model change reused prior result", conflict.Code)
					}
				} else {
					raw, err = base64.StdEncoding.DecodeString(result.Data[0]["b64_json"])
					if err != nil {
						t.Fatal(err)
					}
				}
				if _, format, err := image.Decode(bytes.NewReader(raw)); err != nil || format != "png" {
					t.Fatal("invalid image", format, err)
				}
				if calls.Load() != 1 || prepares.Load() != 1 {
					t.Fatal("duplicate upstream generation", calls.Load(), prepares.Load())
				}
				if _, err := os.Stat(filepath.Join(s.cfg.DataDir, "chatgpt_models.json")); err == nil {
					t.Fatal("explicit image route polluted chat discovery")
				}
			})
		}
	}
}

func TestImage25GIFRejectedBeforeTaskOrQuotaReservation(t *testing.T) {
	for _, model := range []string{"gpt-image-2.5-sunburst", "gpt-image-2.5-flare"} {
		for _, path := range []string{"/v1/images/generations", "/v1/images/edits", "/api/image-tasks/generations", "/api/image-tasks/edits"} {
			s := imageTaskTestServer(t)
			w := httptest.NewRecorder()
			s.Handler().ServeHTTP(w, imageOutputRequest(t, path, "json", map[string]any{"model": model, "prompt": "ball", "client_task_id": "invalid", "output_format": "gif"}))
			if w.Code != 400 || !strings.Contains(w.Body.String(), `"param":"output_format"`) || len(s.imageTasks) != 0 {
				t.Fatalf("%s %s: %d %s", model, path, w.Code, w.Body.String())
			}
		}
	}
}

func TestImage25DoesNotRegenerateAfterUpstreamFailure(t *testing.T) {
	for _, model := range []string{"gpt-image-2.5-sunburst", "gpt-image-2.5-flare"} {
		for _, async := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/async=%v", model, async), func(t *testing.T) {
				s := imageTaskTestServer(t)
				s.cfg.ChatMaxRetries = 3
				s.cfg.ChatRetryCodes = map[int]bool{502: true}
				_, _, _, err := s.store.AddAccounts(nil, []map[string]any{{"access_token": "jwt.header.one", "pool": "basic"}, {"access_token": "jwt.header.two", "pool": "basic"}})
				if err != nil {
					t.Fatal(err)
				}
				var calls atomic.Int32
				upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					switch r.URL.Path {
					case "/":
						io.WriteString(w, `<html data-build="test"></html>`)
					case "/backend-api/sentinel/chat-requirements/prepare":
						writeJSON(w, 200, map[string]any{"prepare_token": "test"})
					case "/backend-api/sentinel/chat-requirements/finalize":
						writeJSON(w, 200, map[string]any{"token": "test"})
					case "/backend-api/f/conversation/prepare":
						writeJSON(w, 200, map[string]any{"status": "ok", "conduit_token": nil})
					case "/backend-api/f/conversation":
						calls.Add(1)
						writeJSON(w, 502, map[string]any{"error": map[string]any{"message": "upstream unavailable"}})
					default:
						t.Error("unexpected endpoint", r.URL.Path)
						http.NotFound(w, r)
					}
				}))
				defer upstream.Close()
				s.openAIImage = provider.NewOpenAIImage(upstream.URL, upstream.Client(), nil, 30*time.Second)
				path := "/v1/images/generations"
				if async {
					path = "/api/image-tasks/generations"
				}
				w := imageTaskCall(s, "POST", path, "api-secret", fmt.Sprintf(`{"model":%q,"prompt":"ball","client_task_id":"failed-model"}`, model))
				if async {
					if w.Code != 202 {
						t.Fatal("submission failed", w.Code)
					}
					deadline := time.Now().Add(5 * time.Second)
					for {
						w = imageTaskCall(s, "GET", "/api/image-tasks/failed-model", "api-secret", "")
						var task imageTaskState
						json.Unmarshal(w.Body.Bytes(), &task)
						if task.Status == "error" {
							break
						}
						if task.Status == "success" || time.Now().After(deadline) {
							t.Fatal("expected terminal error", w.Body.String())
						}
						time.Sleep(10 * time.Millisecond)
					}
				} else if w.Code != 502 {
					t.Fatalf("unexpected status %d %s", w.Code, w.Body.String())
				}
				if calls.Load() != 1 {
					t.Fatal("upstream failure triggered duplicate generation", calls.Load())
				}
			})
		}
	}
}
