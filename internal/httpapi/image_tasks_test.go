func imageTaskTestServer(t *testing.T) *Server {
	t.Helper()
	root := t.TempDir()
	cfg := testConfig()
	cfg.RootDir, cfg.DataDir = root, root
	cfg.ConfigPath = filepath.Join(root, "config.json")
	cfg.AccountsPath = filepath.Join(root, "accounts.json")
	cfg.AuthKeysPath = filepath.Join(root, "auth_keys.json")
	cfg.ImageDataDir = filepath.Join(root, "images")
	cfg.QueuePath = filepath.Join(root, "queue.json")
	cfg.RequestTimeout = 30 * time.Second
	return New(cfg)
}

func imageTaskCall(s *Server, method, path, key, body string) *httptest.ResponseRecorder {
	r := httptest.NewRequest(method, path, strings.NewReader(body))
	r.Header.Set("Authorization", "Bearer "+key)
	r.Header.Set("Content-Type", "application/json")
	w := httptest.NewRecorder()
	s.Handler().ServeHTTP(w, r)
	return w
}

func TestImageTaskAsyncLifecycleSurvivesCallerCancellation(t *testing.T) {
	for _, tc := range []struct {
		name, mode      string
		busyDownloads   int
		wantError       bool
		upstreamFailure string
	}{
		{"generate", "generations", 0, false, ""}, {"edit", "edits", 0, false, ""},
		{"storage-busy-recover", "edits", 1, false, ""}, {"storage-busy-fail", "edits", 3, true, ""},
		{"terminal-stream-error", "generations", 0, true, "stream"},
		{"terminal-poll-error", "edits", 0, true, "poll"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			mode := tc.mode
			var generateCalls, downloadCalls, metadataCalls, pollCalls atomic.Int32
			const rejection = "生成的图片可能违反了关于潜在欺诈或诈骗活动的防护限制。"
			failedMessage := map[string]any{"author": map[string]any{"role": "assistant"}, "status": "finished_successfully", "end_turn": true, "metadata": map[string]any{"is_error": true}, "content": map[string]any{"content_type": "text", "parts": []any{rejection}}}
			s := imageTaskTestServer(t)
			s.cfg.ChatMaxRetries = 2
			s.cfg.ChatRetryCodes = map[int]bool{502: true, 422: true, 504: true}
			if _, _, _, err := s.store.AddAccounts(nil, []map[string]any{{"access_token": "jwt.header.payload", "email": "async@example.test", "pool": "basic"}}); err != nil {
				t.Fatal(err)
			}
			started, release := make(chan struct{}), make(chan struct{})
			defer func() {
				select {
				case <-release:
				default:
					close(release)
				}
			}()
			fileID := "file_000000001234567890abcdef12345678"
			output := image.NewRGBA(image.Rect(0, 0, 2, 2))
			output.Set(1, 1, color.RGBA{R: 255, A: 255})
			var generated bytes.Buffer
			if err := png.Encode(&generated, output); err != nil {
				t.Fatal(err)
			}
			var upstream *httptest.Server
			upstream = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				switch r.URL.Path {
				case "/backend-api/files":
					writeJSON(w, 200, map[string]any{"file_id": "file_reference", "upload_url": upstream.URL + "/reference-upload"})
				case "/reference-upload":
					raw, _ := io.ReadAll(r.Body)
					if !bytes.Equal(raw, tinyPNG) {
						t.Error("reference bytes did not reach upstream")
					}
					w.WriteHeader(201)
				case "/backend-api/files/file_reference/uploaded":
					writeJSON(w, 200, map[string]any{"status": "success"})
				case "/":
					_, _ = w.Write([]byte(`<html data-build="test-build"></html>`))
				case "/backend-api/sentinel/chat-requirements/prepare":
					writeJSON(w, 200, map[string]any{"prepare_token": "test"})
				case "/backend-api/sentinel/chat-requirements/finalize":
					writeJSON(w, 200, map[string]any{"token": "test"})
				case "/backend-api/f/conversation/prepare":
					writeJSON(w, 200, map[string]any{"conduit_token": "test"})
				case "/backend-api/f/conversation":
					if mode == "edits" {
						raw, _ := io.ReadAll(r.Body)
						if !bytes.Contains(raw, []byte("file_reference")) {
							t.Error("edit conversation missing reference")
						}
					}
					if generateCalls.Add(1) == 1 {
						close(started)
					} else {
						t.Error("download failure retriggered image generation")
					}
					select {
					case <-release:
					case <-r.Context().Done():
						return
					}
					w.Header().Set("Content-Type", "text/event-stream")
					if tc.upstreamFailure == "stream" {
						raw, _ := json.Marshal(map[string]any{"conversation_id": "conversation-1", "message": failedMessage})
						_, _ = w.Write(append(append([]byte("data: "), raw...), []byte("\n\ndata: [DONE]\n\n")...))
						return
					}
					_, _ = w.Write([]byte("data: {\"conversation_id\":\"conversation-1\",\"message\":{\"content\":{\"parts\":[\"file-service://" + fileID + "\"]}}}\n\ndata: [DONE]\n\n"))
				case "/backend-api/conversation/conversation-1":
					pollCalls.Add(1)
					if tc.upstreamFailure == "poll" {
						writeJSON(w, 200, map[string]any{"mapping": map[string]any{"final": map[string]any{"message": failedMessage}}})
						return
					}
					writeHTTPAPIGeneratedImageConversation(w, fileID)
				case "/backend-api/files/" + fileID + "/download":
					metadataCalls.Add(1)
					writeJSON(w, 200, map[string]any{"download_url": upstream.URL + "/blob"})
				case "/blob":
					w.Header().Set("Content-Type", "image/png")
					if downloadCalls.Add(1) <= int32(tc.busyDownloads) {
						_, _ = w.Write([]byte("\xef\xbb\xbf<?xml version=\"1.0\"?><Error><Code>ServerBusy</Code></Error>"))
					} else {
						_, _ = w.Write(generated.Bytes())
					}
				default:
					http.NotFound(w, r)
				}
			}))
			defer func() {
				select {
				case <-release:
				default:
					close(release)
				}
				upstream.Close()
			}()
			s.openAIImage = provider.NewOpenAIImage(upstream.URL, upstream.Client(), nil, 30*time.Second)
			body := `{"client_task_id":"async-one","model":"gpt-image-2","prompt":"a cat","n":1}`
			if mode == "edits" {
				body = strings.TrimSuffix(body, "}") + `,"images":["data:image/png;base64,` + base64.StdEncoding.EncodeToString(tinyPNG) + `"]}`
			}
			ctx, cancel := context.WithCancel(context.Background())
			r := httptest.NewRequest(http.MethodPost, "/api/image-tasks/"+mode, strings.NewReader(body)).WithContext(ctx)
			r.Header.Set("Authorization", "Bearer api-secret")
			r.Header.Set("Content-Type", "application/json")
			w := httptest.NewRecorder()
			s.Handler().ServeHTTP(w, r)
			cancel()
			if w.Code != 202 {
				t.Fatalf("submit: %d %s", w.Code, w.Body.String())
			}
			select {
			case <-started:
			case <-time.After(5 * time.Second):
				t.Fatalf("background generation did not start: %s", imageTaskCall(s, "GET", "/api/image-tasks/async-one", "api-secret", "").Body.String())
			}
			for i := 0; i < 5; i++ {
				w = imageTaskCall(s, "POST", "/api/image-tasks/"+mode, "api-secret", body)
				if w.Code != 202 {
					t.Fatalf("idempotent submission: %d", w.Code)
				}
				w = imageTaskCall(s, "GET", "/api/image-tasks/async-one", "api-secret", "")
				if !strings.Contains(w.Body.String(), `"status":"running"`) {
					t.Fatal(w.Body.String())
				}
			}
			w = imageTaskCall(s, "POST", "/api/image-tasks/"+mode, "api-secret", strings.Replace(body, "a cat", "a dog", 1))
			if w.Code != 409 {
				t.Fatalf("conflicting duplicate: %d", w.Code)
			}
			w = imageTaskCall(s, "GET", "/api/image-tasks/async-one", "admin-secret", "")
			if w.Code != 404 {
				t.Fatalf("cross-owner read: %d", w.Code)
			}
			close(release)
			deadline := time.After(5 * time.Second)
			for {
				w = imageTaskCall(s, "GET", "/api/image-tasks/async-one", "api-secret", "")
				var task imageTaskState
				if err := json.Unmarshal(w.Body.Bytes(), &task); err != nil {
					t.Fatal(err)
				}
				if task.Status == "error" {
					wantReason := "ServerBusy"
					if tc.upstreamFailure != "" {
						wantReason = rejection
					}
					if !tc.wantError || !strings.Contains(task.Error, wantReason) {
						t.Fatal(task.Error)
					}
					if len(task.Data) != 0 {
						t.Fatal("failed download returned image URLs")
					}
					break
				}
				if task.Status == "success" {
					if tc.wantError {
						t.Fatal("storage error counted as successful image")
					}
					if len(task.Data) != 1 || task.Data[0]["url"] == "" || task.Data[0]["b64_json"] != nil {
						t.Fatalf("missing result: %s", w.Body.String())
					}
					break
				}
				select {
				case <-deadline:
					t.Fatal("task did not finish")
				case <-time.After(10 * time.Millisecond):
				}
			}
			// A new process can query the completed result, and the same request never reruns.
			reloaded := New(s.cfg)
			w = imageTaskCall(reloaded, "POST", "/api/image-tasks/"+mode, "api-secret", body)
			expectedStatus, logStatus := "success", "success"
			if tc.wantError {
				expectedStatus, logStatus = "error", "failed"
			}
			if w.Code != 202 || !strings.Contains(w.Body.String(), `"status":"`+expectedStatus+`"`) {
				t.Fatal(w.Body.String())
			}
			// The worker writes one completed call; acknowledgement, polling, retries
			// and querying after a process restart must not create extra call records.
			assertImageTaskCallLog(t, reloaded, "async-one", logStatus, "/v1/images/"+mode)
			expectedDownloads := tc.busyDownloads + 1
			if tc.wantError {
				expectedDownloads = 3
			}
			if tc.upstreamFailure != "" {
				expectedDownloads = 0
				wantPolls := int32(1)
				if tc.upstreamFailure == "stream" {
					wantPolls = 0
				}
				if pollCalls.Load() != wantPolls {
					t.Fatalf("terminal failure kept polling: %d", pollCalls.Load())
				}
			}
			if generateCalls.Load() != 1 || int(downloadCalls.Load()) != expectedDownloads || metadataCalls.Load() != downloadCalls.Load() {
				t.Fatalf("generation/download/metadata counts: %d/%d/%d", generateCalls.Load(), downloadCalls.Load(), metadataCalls.Load())
			}
			if tc.wantError {
				entries, _ := os.ReadDir(s.cfg.ImageDataDir)
				if len(entries) != 0 {
					t.Fatal("error file was persisted")
				}
			}

		})
	}
}

func TestImageTaskPersistenceAndOwnerIsolation(t *testing.T) {
	s := imageTaskTestServer(t)
	for _, status := range []string{"queued", "running", "success", "error"} {
		task := &imageTaskState{ID: "same-id", OwnerID: status, Status: status, Prompt: "private prompt", Images: [][]byte{[]byte("private input")}, RequestHash: "digest", CreatedAt: time.Now().UTC().Format(time.RFC3339)}
		if err := s.saveImageTaskLocked(task); err != nil {
			t.Fatal(err)
		}
		path := filepath.Join(s.imageTasksDir(), imageTaskKey(status, task.ID)+".json")
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(raw), "private") {
			t.Fatal("persisted private input")
		}
		info, err := os.Stat(path)
		if err != nil || info.Mode().Perm() != 0o600 {
			t.Fatalf("unsafe task file: %v", err)
		}
	}
	reloaded := New(s.cfg)
	if len(reloaded.imageTasks) != 4 {
		t.Fatal("owners replaced each other's task")
	}
	for _, status := range []string{"queued", "running", "success", "error"} {
		task := reloaded.imageTasks[imageTaskKey(status, "same-id")]
		if status == "queued" || status == "running" {
			if task.Status != "error" || !strings.Contains(task.Error, "restarted") {
				t.Fatalf("interrupted task: %+v", task)
			}
		} else if task.Status != status {
			t.Fatalf("terminal result changed: %+v", task)
		}
	}
	// Storage failure must reject the request before any upstream work starts.
	blocked := imageTaskTestServer(t)
	if err := os.WriteFile(blocked.imageTasksDir(), []byte("not a directory"), 0o600); err != nil {
		t.Fatal(err)
	}
	w := imageTaskCall(blocked, "POST", "/api/image-tasks/generations", "api-secret", `{"client_task_id":"fail","prompt":"cat"}`)
	if w.Code != 503 || len(blocked.imageTasks) != 0 {
		t.Fatalf("accepted without persistence: %d", w.Code)
	}
}

