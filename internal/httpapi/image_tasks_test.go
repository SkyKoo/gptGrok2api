func assertImageTaskCallLog(t *testing.T, s *Server, taskID, status, endpoint string) {
	t.Helper()
	w := imageTaskCall(s, http.MethodGet, "/api/logs?type=call&limit=20", "admin-secret", "")
	if w.Code != http.StatusOK {
		t.Fatalf("logs API: %d %s", w.Code, w.Body.String())
	}
	var result struct {
		Total int              `json:"total"`
		Items []map[string]any `json:"items"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &result); err != nil {
		t.Fatal(err)
	}
	if result.Total != 1 || len(result.Items) != 1 {
		t.Fatalf("expected one execution log, got %s", w.Body.String())
	}
	row := result.Items[0]
	detail := mapValue(row["detail"])
	shape := mapValue(detail["request_shape"])
	if stringValue(detail["status"]) != status || stringValue(detail["endpoint"]) != endpoint ||
		stringValue(detail["model"]) != "gpt-image-2" || stringValue(shape["client_task_id"]) != taskID ||
		shape["async"] != true || !strings.HasPrefix(stringValue(row["id"]), "image-task-") {
		t.Fatalf("incorrect execution log: %s", w.Body.String())
	}
	outputs, _ := detail["output_images"].([]any)
	if status == "success" && len(outputs) != 1 {
		t.Fatalf("missing generated image in log: %s", w.Body.String())
	}
	if status == "failed" && stringValue(detail["error"]) == "" {
		t.Fatalf("missing error in log: %s", w.Body.String())
	}
	if strings.Contains(w.Body.String(), "api-secret") || strings.Contains(w.Body.String(), "jwt.header.payload") {
		t.Fatal("credentials leaked into the call log")
	}
}

func TestAsyncJSONImageEditValidation(t *testing.T) {
	s := imageTaskTestServer(t)
	t.Setenv("GO_ALLOW_PRIVATE_IMAGE_URLS", "false")
	for _, fields := range []string{
		`"images":[]`, `"images":[""]`, `"images":["data:image/png;base64,!!!"]`,
		`"images":["http://127.0.0.1/a"]`, `"images":["http://169.254.169.254/latest/meta-data"]`,
		`"images":["http://user:password@example.com/a"]`,
		`"n":0,"images":["x"]`, `"n":3,"images":["x"]`, `"n":1.5,"images":["x"]`,
		`"n":9223372036854775808,"images":["x"]`, `"mask":"x","images":["x"]`,
		`"images":["x","x","x","x","x","x","x","x"]`,
	} {
		w := imageTaskCall(s, "POST", "/api/image-tasks/edits", "api-secret", `{"client_task_id":"bad","prompt":"edit",`+fields+`}`)
		if w.Code != 400 {
			t.Errorf("invalid edit accepted: %d", w.Code)
		}
		if strings.Contains(w.Body.String(), "password") {
			t.Error("reference URL leaked")
		}
	}
	if len(s.imageTasks) != 0 {
		t.Fatal("invalid input created tasks")
	}
	w := imageTaskCall(s, "POST", "/api/image-tasks/edits", "wrong-key", `{}`)
	if w.Code != 401 {
		t.Fatalf("unauthorized edit: %d", w.Code)
	}
}

func TestAsyncImageEditMultipartRemainsSupported(t *testing.T) {
	s := imageTaskTestServer(t)
	var body bytes.Buffer
	writer := multipart.NewWriter(&body)
	_ = writer.WriteField("client_task_id", "multipart-edit")
	_ = writer.WriteField("prompt", "edit")
	_ = writer.WriteField("model", "gpt-image-2")
	file, err := writer.CreateFormFile("image[]", "input.png")
	if err != nil {
		t.Fatal(err)
	}
	_, _ = file.Write(tinyPNG)
	_ = writer.Close()
	r := httptest.NewRequest("POST", "/api/image-tasks/edits", &body)
	r.Header.Set("Content-Type", writer.FormDataContentType())
	r.Header.Set("Authorization", "Bearer api-secret")
	w := httptest.NewRecorder()
	s.Handler().ServeHTTP(w, r)
	if w.Code != 202 {
		t.Fatalf("multipart edit: %d %s", w.Code, w.Body.String())
	}
	for deadline := time.Now().Add(3 * time.Second); time.Now().Before(deadline); {
		w = imageTaskCall(s, "GET", "/api/image-tasks/multipart-edit", "api-secret", "")
		if strings.Contains(w.Body.String(), `"status":"error"`) {
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
	t.Fatal("multipart task did not finish")
}

func TestImagePollingDeadlinePreservesUpstreamReason(t *testing.T) {
	s := imageTaskTestServer(t)
	s.cfg.ChatMaxRetries = 2
	s.cfg.ChatRetryCodes = map[int]bool{504: true}
	if _, _, _, err := s.store.AddAccounts(nil, []map[string]any{{"access_token": "jwt.header.payload", "pool": "basic"}}); err != nil {
		t.Fatal(err)
	}
	var starts, polls atomic.Int32
	client := &http.Client{Transport: updateRoundTripFunc(func(r *http.Request) (*http.Response, error) {
		raw := `{}`
		switch r.URL.Path {
		case "/":
			raw = `<html data-build="test"></html>`
		case "/backend-api/sentinel/chat-requirements/prepare":
			raw = `{"prepare_token":"test"}`
		case "/backend-api/sentinel/chat-requirements/finalize":
			raw = `{"token":"test"}`
		case "/backend-api/f/conversation/prepare":
			raw = `{"conduit_token":"test"}`
		case "/backend-api/f/conversation":
			starts.Add(1)
			raw = "data: {\"conversation_id\":\"conversation-timeout\"}\n\ndata: [DONE]\n\n"
		case "/backend-api/conversation/conversation-timeout":
			polls.Add(1)
		default:
			t.Errorf("unexpected path %s", r.URL.Path)
		}
		return &http.Response{StatusCode: 200, Header: make(http.Header), Body: io.NopCloser(strings.NewReader(raw)), Request: r}, nil
	})}
	s.openAIImage = provider.NewOpenAIImage("http://upstream.invalid", client, nil, time.Second)
	ctx, cancel := provider.WithImageTaskTimeout(context.Background(), 100*time.Millisecond)
	defer cancel()
	_, err := s.generateOpenAIImageData(nil, ctx, "test", "gpt-image-2", "1024x1024", "auto", nil, "url", "http://cfm.invalid", 1, provider.ImageOutputOptions{})
	if err == nil || !strings.Contains(err.Error(), "last poll error: upstream response contained no image reference") {
		t.Fatalf("lost polling diagnostic: %v", err)
	}
	if starts.Load() != 1 || polls.Load() != 1 {
		t.Fatalf("unexpected retry: starts=%d polls=%d", starts.Load(), polls.Load())
	}
}
